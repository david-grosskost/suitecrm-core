<?php

// Shared base configuration of every SuiteCRM instance. Appended once to
// public/legacy/config_override.php by suitecrm-install; afterwards the
// administrator owns these settings. Keep the first line alone: only the lines
// after it are appended.
//
// The French settings (language, date and time formats, euro, number
// separators, CSV delimiter) are no longer here: they come from the
// french-locale extension, installed before the administrator's preferences
// are aligned on them (scripts/install.sh).

/** @var array<string, mixed> $sugar_config Set by SuiteCRM before this file runs */

// A password generated by the system (the administrator's on a server, see
// ADMIN_PASSWORD_ONCE, or one sent by "forgot password") must be changed at
// the first login with it. Saving the new one needs the upstream-fixes
// extension (SuiteCRM bug).
$passwordsetting = $sugar_config['passwordsetting'] ?? [];
$sugar_config['passwordsetting'] = array_merge(is_array($passwordsetting) ? $passwordsetting : [], [
    'systexpiration' => '2', // after a number of logins...
    'systexpirationlogin' => '1', // ...one
]);
unset($passwordsetting);
